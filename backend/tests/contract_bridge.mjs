// Exercise the real unchanged client, validators, terrain and site mapper.
import assert from 'node:assert/strict';
import {V3Session,HttpTransport} from '../../sandbox/web/v3-api.js';
import {schedule} from '../../sandbox/web/v3-contract.js';
import {terrainGeometry} from '../../sandbox/web/v3-map.js';
import {locateBuilding} from '../../sandbox/web/geography.js';

const base=process.argv[2];
let checks=0;
const check=(value,message)=>{assert.ok(value,message);checks++;};
const transport=new HttpTransport((path,options)=>fetch(base+path,options));
const setup={bounds:{west:114,south:22.45,east:114.2,north:22.6},start:'2024-01-31',end:'2024-05-31',step:'quarter',policyScope:{policyId:'test-policy',tags:['housing-affordability']}};
const file=new File(['%PDF-1.4\nReal HTTP contract check\n'],'plan.pdf',{type:'application/pdf'});
const form=()=>{const f=new FormData();f.append('metadata',JSON.stringify(setup));f.append('plan',file,file.name);return f;};
const first=await transport.request('/initializations',form(),undefined,'multipart_retry');
const retry=await transport.request('/initializations',form(),undefined,'multipart_retry');
check(first.initializationId===retry.initializationId,'new multipart boundaries replay same initialization');
check(first.items.some(i=>i.id==='authority'&&i.value.includes('instead')),'policy override must be visible in review');
check(first.items.some(i=>i.description.includes('not interpreted')),'PDF limitation disclosed');
const session=new V3Session(transport,{today:'2026-10-16',sleep:async()=>new Promise(resolve=>setTimeout(resolve,5))});
await session.initialize(setup,file);
check(session.state==='review','initialize transitions to review');
await session.confirm(true);
check(session.state==='confirmed','version confirmation acknowledged');
await session.simulate();
check(session.state==='ready','durable asynchronous job resolves');
check(JSON.stringify(session.run.snapshots.map(f=>f.date))===JSON.stringify(schedule(setup)),'frontend output schedule matches anchor dates');
const frame=await session.snapshot(1);
check(frame.height.length===1e6&&frame.landType.length===1e6,'real million-cell layers validate');
check(frame.pollution.length===0,'unmodeled pollution sentinel normalizes to empty');
check(frame.roads.length===0&&frame.mtr.length===0&&frame.powerLines.length===0,'no invented infrastructure lines');
check(frame.zones.length===4,'canonical completed footprints are zones');
check(frame.zones.every(z=>z.boundary[0][0]===z.boundary.at(-1)[0]&&z.boundary[0][1]===z.boundary.at(-1)[1]),'all zone polygons closed');
const geometry=terrainGeometry(frame),positions=geometry.attributes.position.array;
check(Array.from(positions).every((v,i)=>i%3!==1||v===0),'tower meshes are never encoded as terrain height');
geometry.dispose();
const exported=await fetch(base+'/api/v3/simulations/'+session.run.simulationId+'/export').then(r=>r.json());
check(exported.monthlyStates.length===5&&exported.monthlyStates[2].month==='2024-03-31','all internal monthly states saved with original day anchor');
const overview=await fetch(base+'/api/state').then(r=>r.json());
check(overview.world.buildings.every(b=>Number.isFinite(locateBuilding(b).x)),'legacy overview uses valid unchanged display sites');
check(overview.world.buildings.length===2&&overview.world.sourceDate==='2024-01-31'&&overview.world.metrics.airQuality===null,'overview opens the first saved month with canonical objects and unavailable climate');
check(exported.run.providerMetrics.summary.callCount>0&&exported.run.provenance.includes('synthetic'),'fixture provenance and measured calls retained');
process.stdout.write(JSON.stringify({state:session.state,snapshots:session.run.snapshots.length,checks}));
